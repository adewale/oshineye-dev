import { test, expect } from 'bun:test';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, unlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { verifyRaynerExport, verifyPoppyExport, sectionText } from '../tools/verify-rayner-export.mjs';

const hash = text => createHash('sha256').update(text).digest('hex');
const markers = path => ({
  headers: { begin: `# Rayner explainers at ${path}: generated by \`npm run site:export\`; regenerate rather than edit.`, end: `# End of Rayner explainers at ${path}.` },
  llms: { begin: `<!-- rayner:begin ${path} -->`, end: `<!-- rayner:end ${path} -->` },
});
const block = ({ begin, end }, body) => `${begin}\n${body}\n${end}\n`;

/** A site holding two exports, as oshineye.dev does: each owns its subtree and one section of each shared file. */
function site() {
  const repo = mkdtempSync(join(tmpdir(), 'rayner-export-'));
  const root = join(repo, 'site');
  const r = markers('/projects/rayner'), p = markers('/projects/poppy');
  const sections = {
    rayner: { headers: block(r.headers, '/projects/rayner/cache\n  Content-Security-Policy: strict'), llms: block(r.llms, '## Explainers\n\n- [Cache](https://oshineye.dev/projects/rayner/cache)') },
    poppy: { headers: block(p.headers, '/projects/poppy/poppy\n  Content-Security-Policy: strict'), llms: block(p.llms, '## Poppy, explained\n\n- [Poppy](https://oshineye.dev/projects/poppy/poppy)') },
  };
  const write = (file, text) => writeFileSync(join(root, file), text);
  mkdirSync(join(root, 'projects/rayner'), { recursive: true });
  mkdirSync(join(root, 'projects/poppy'), { recursive: true });
  write('_headers', '# The host\'s own rules\n/*\n  X-Frame-Options: DENY\n\n' + sections.rayner.headers + '\n' + sections.poppy.headers);
  write('llms.txt', '# Rayner explainers\n\n> Intro.\n\n' + sections.rayner.llms + '\n' + sections.poppy.llms);
  write('projects/rayner.html', 'host page');
  write('projects/poppy.html', 'host page');
  write('projects/rayner/cache.html', 'scene');
  write('projects/poppy/poppy.html', 'chapter');
  const manifest = (name, file, body, m) => ({
    version: 2, path: `/projects/${name}`, build: {},
    files: [{ path: `/projects/${name}/${file}`, sha256: hash(body) }],
    sections: [
      { path: '/_headers', ...m.headers, sha256: hash(sections[name].headers) },
      { path: '/llms.txt', ...m.llms, sha256: hash(sections[name].llms) },
    ],
  });
  const manifests = { rayner: manifest('rayner', 'cache.html', 'scene', r), poppy: manifest('poppy', 'poppy.html', 'chapter', p) };
  const save = name => write(`projects/${name}/deployment.json`, JSON.stringify(manifests[name]));
  save('rayner'); save('poppy');
  return { repo, root, write, manifests, save, sections };
}

test('a section runs from its begin line to the newline after its end line, as Rayner hashes it', () => {
  const m = markers('/projects/rayner').llms;
  expect(sectionText(`before\n${m.begin}\nlist\n${m.end}\nafter\n`, m.begin, m.end)).toBe(`${m.begin}\nlist\n${m.end}\n`);
  expect(sectionText(`${m.begin}\nlist\n${m.end}`, m.begin, m.end)).toBe(`${m.begin}\nlist\n${m.end}\n`);
  expect(() => sectionText(`${m.begin}\n${m.begin}\n${m.end}\n`, m.begin, m.end)).toThrow(/once/);
  expect(() => sectionText(`${m.begin}\nlist\n`, m.begin, m.end)).toThrow(/no end line/);
});

test('each export is verified by its own files and its own sections of the shared files', async () => {
  const { repo, root, write, manifests, save, sections } = site();
  try {
    expect(await verifyRaynerExport(root)).toBe(3);
    expect(await verifyPoppyExport(root)).toBe(3);
    // The host's rules and the other collection's section may change without staling either manifest.
    write('_headers', '# The host\'s own rules, edited\n/*\n  X-Frame-Options: SAMEORIGIN\n\n' + sections.rayner.headers + '\n' + sections.poppy.headers);
    await verifyRaynerExport(root);
    await verifyPoppyExport(root);
    // Its own section may not.
    write('_headers', sections.rayner.headers.replace('strict', 'loose') + '\n' + sections.poppy.headers);
    await expect(verifyRaynerExport(root)).rejects.toThrow(/_headers's rayner section has a different digest/);
    await verifyPoppyExport(root);
    write('_headers', sections.rayner.headers + '\n' + sections.poppy.headers);
    write('llms.txt', sections.rayner.llms + sections.rayner.llms + sections.poppy.llms);
    await expect(verifyRaynerExport(root)).rejects.toThrow(/once/);
    write('llms.txt', sections.rayner.llms + '\n' + sections.poppy.llms);
    await verifyRaynerExport(root);
  } finally { rmSync(repo, { recursive: true, force: true }); }
});

test('a tampered, missing or unlisted file, a gallery index, or a foreign path fails verification', async () => {
  const { repo, root, write, manifests, save } = site();
  try {
    write('projects/rayner/cache.html', 'tampered');
    await expect(verifyRaynerExport(root)).rejects.toThrow(/cache\.html has a different digest/);
    write('projects/rayner/cache.html', 'scene');
    write('projects/rayner/old.html', 'orphan');
    await expect(verifyRaynerExport(root)).rejects.toThrow(/unlisted rayner file.*old\.html/);
    unlinkSync(join(root, 'projects/rayner/old.html'));
    unlinkSync(join(root, 'projects/rayner/cache.html'));
    await expect(verifyRaynerExport(root)).rejects.toThrow(/cache\.html is missing/);
    write('projects/rayner/cache.html', 'scene');
    // An export without --index none writes and pins a generic gallery over the host's page.
    write('projects/rayner/index.html', 'gallery');
    manifests.rayner.files.push({ path: '/projects/rayner/index.html', sha256: hash('gallery') });
    save('rayner');
    await expect(verifyRaynerExport(root)).rejects.toThrow(/--index none/);
    manifests.rayner.files.pop();
    unlinkSync(join(root, 'projects/rayner/index.html'));
    // Another collection's file, a shared file, and a path out of the site are not this export's.
    for (const path of ['/projects/poppy/poppy.html', '/_headers', '/projects/rayner/../outside', '/projects/rayner.html']) {
      manifests.rayner.files.push({ path, sha256: hash('x') });
      save('rayner');
      await expect(verifyRaynerExport(root)).rejects.toThrow(/invalid manifest path/);
      manifests.rayner.files.pop();
    }
    save('rayner');
    await verifyRaynerExport(root);
  } finally { rmSync(repo, { recursive: true, force: true }); }
});

test('a version 1 manifest, a manifest for another path, or another collection\'s section is refused', async () => {
  const { repo, root, manifests, save } = site();
  try {
    manifests.rayner.version = 1;
    save('rayner');
    await expect(verifyRaynerExport(root)).rejects.toThrow(/expected version 2/);
    manifests.rayner.version = 2;
    manifests.rayner.path = '/projects/poppy';
    save('rayner');
    await expect(verifyRaynerExport(root)).rejects.toThrow(/expected version 2 for \/projects\/rayner/);
    manifests.rayner.path = '/projects/rayner';
    const own = manifests.rayner.sections[1];
    manifests.rayner.sections[1] = manifests.poppy.sections[1];
    save('rayner');
    await expect(verifyRaynerExport(root)).rejects.toThrow(/invalid \/llms\.txt section/);
    manifests.rayner.sections[1] = own;
    manifests.rayner.sections.pop();
    save('rayner');
    await expect(verifyRaynerExport(root)).rejects.toThrow(/exactly its sections/);
  } finally { rmSync(repo, { recursive: true, force: true }); }
});

test('the host page the path is served from must exist', async () => {
  const { repo, root } = site();
  try {
    unlinkSync(join(root, 'projects/poppy.html'));
    await expect(verifyPoppyExport(root)).rejects.toThrow(/host page \/projects\/poppy\.html/);
  } finally { rmSync(repo, { recursive: true, force: true }); }
});
